// Bakes each map's spot table and land bitmap, so the contract can roll a layout without carving
// terrain or trying thousands of cells. `npm run gen-map-data`, then commit the output. A test fails if
// the committed files drift from the map definitions.
import { canStand, getGrids, H, MAP_DEFS, MAP_IDS, rosterOf, spotTags, TAG_ORDER, W } from '../src/lib/game/map';
import { CATEGORY, FOOTPRINT, HABITAT } from '../src/lib/game/mapDefs';
import { sha256, toHex } from '../src/lib/game/random';
import type { Kind, MapId } from '../src/lib/game/types';

const GRID = 3;
const MAX_SPOTS = 500;
const MIN_APART = 5;
/** Every kind gets at least this many well-spread spots before the rest of the table fills in. */
const SPOTS_PER_KIND = 45;

type Candidate = { x: number; y: number; tags: number; kindMask: number };

function candidates(id: MapId): Candidate[] {
  const grids = getGrids(id);
  const roster = rosterOf(id);
  const found: Candidate[] = [];
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const onGrid = x % GRID === 0 && y % GRID === 0;
      let kindMask = 0;
      let picky = false;
      roster.forEach((kind, bit) => {
        if (!canStand(grids, kind, x, y)) return;
        kindMask |= 1 << bit;
        if (HABITAT[kind]) picky = true;
      });
      // Shoreline kinds fit in a band a few pixels wide, which a coarse grid would mostly miss.
      if (!kindMask || (!onGrid && !picky)) continue;
      const tags = spotTags(grids, x, y).reduce((bits, tag) => bits | (1 << TAG_ORDER.indexOf(tag)), 0);
      found.push({ x, y, tags, kindMask });
    }
  }
  return found;
}

const squared = (a: Candidate, b: Candidate) => (a.x - b.x) ** 2 + (a.y - b.y) ** 2;

/** Keeps taking the candidate furthest from everything chosen for this purpose, so the picks stay even. */
function spreadPicks(pool: Candidate[], chosen: Candidate[], count: number, among: (c: Candidate) => boolean): void {
  const eligible = pool.filter(among);
  const nearest = eligible.map((c) => {
    let best = Infinity;
    for (const s of chosen) if (among(s)) best = Math.min(best, squared(c, s));
    return best;
  });
  const nearestAny = eligible.map((c) => {
    let best = Infinity;
    for (const s of chosen) best = Math.min(best, squared(c, s));
    return best;
  });
  for (let picked = chosen.filter(among).length; picked < count && chosen.length < MAX_SPOTS; picked++) {
    let bestAt = -1;
    for (let i = 0; i < eligible.length; i++) {
      if (nearestAny[i] < MIN_APART * MIN_APART) continue;
      if (bestAt < 0 || nearest[i] > nearest[bestAt]) bestAt = i;
    }
    if (bestAt < 0) return;
    const spot = eligible[bestAt];
    chosen.push(spot);
    for (let i = 0; i < eligible.length; i++) {
      const d = squared(eligible[i], spot);
      nearest[i] = Math.min(nearest[i], d);
      nearestAny[i] = Math.min(nearestAny[i], d);
    }
  }
}

function thin(id: MapId, pool: Candidate[]): Candidate[] {
  const roster = rosterOf(id);
  const chosen: Candidate[] = [];
  const fits = (bit: number) => pool.filter((c) => c.kindMask & (1 << bit)).length;
  // Scarcest first, because a shoreline spot chosen for boats also counts for everything else that fits there.
  const scarcest = roster.map((_, bit) => bit).sort((a, b) => fits(a) - fits(b) || a - b);
  for (const bit of scarcest) spreadPicks(pool, chosen, SPOTS_PER_KIND, (c) => (c.kindMask & (1 << bit)) !== 0);
  spreadPicks(pool, chosen, MAX_SPOTS, () => true);
  return chosen.sort((a, b) => a.y - b.y || a.x - b.x);
}

function landBitmap(id: MapId): Uint8Array {
  const { land } = getGrids(id);
  const bytes = new Uint8Array((W * H) / 8);
  for (let i = 0; i < W * H; i++) if (land[i]) bytes[i >> 3] |= 1 << (i & 7);
  return bytes;
}

function spotBytes(spots: Candidate[]): Uint8Array {
  const bytes = new Uint8Array(spots.length * 6);
  const view = new DataView(bytes.buffer);
  spots.forEach((s, i) => {
    view.setUint16(i * 6, s.x, true);
    view.setUint8(i * 6 + 2, s.y);
    view.setUint8(i * 6 + 3, s.tags);
    view.setUint16(i * 6 + 4, s.kindMask, true);
  });
  return bytes;
}

function kindTable(id: MapId): string {
  const rows = rosterOf(id).map((kind: Kind, bit) => {
    const [w, h] = FOOTPRINT[kind];
    return `| ${bit} | ${kind} | ${MAP_DEFS[id].roster[kind]} | ${CATEGORY[kind]} | ${w} | ${h} | ${HABITAT[kind] ? 'yes' : 'no'} |`;
  });
  return [`### ${id}`, '', '| Bit | Kind | Count | Category | Width | Height | Habitat kind |', '|---|---|---|---|---|---|---|', ...rows].join('\n');
}

const README = (tables: string, files: string) => `# Map data for the contract

Generated by \`npm run gen-map-data\` (\`scripts/gen-map-data.ts\`). Don't edit by hand. The contract
reads these with \`include_bytes!\`. The same tables are in \`src/lib/game/generated/map-data.json\` for the browser.

## land-<map>.bin

${(W * H) / 8} bytes. One bit per pixel of the ${W}×${H} map, row by row from the top, left to right, least
significant bit first. Pixel (x, y) is bit \`i & 7\` of byte \`i >> 3\`, where \`i = y * ${W} + x\`. 1 is land.
Anything off the map is not land.

## spots-<map>.bin

6 bytes per spot, with no header, so the spot count is the file size divided by 6. Little-endian. A spot's
index in the file is the index the layout roll draws.

| Offset | Type | Field |
|---|---|---|
| 0 | u16 | x |
| 2 | u8 | y |
| 3 | u8 | tags, a bit set |
| 4 | u16 | kindMask: bit n is set if the kind at bit n of that map's table below fits here |

Tag bits, in the order a landmark's tag list is read. This order is part of the rules, because the
\`detail\` clue chooses from that list by index:

| Bit | Tag |
|---|---|
${TAG_ORDER.map((tag, bit) => `| ${bit} | ${tag} |`).join('\n')}

## Kinds, per map

Roster order, used for the bits of \`kindMask\` and for the layout's pool. Footprints are in pixels: the box of a landmark
at (x, y) starts at left = x - floor(width / 2) and top = y - height, as in \`clearsPlaced\` in \`map.ts\`.

${tables}

## Files

| File | Bytes | SHA-256 |
|---|---|---|
${files}
`;

export default function generate(): Record<string, string | Uint8Array> {
  const outputs: Record<string, string | Uint8Array> = {};
  const fileRows: string[] = [];
  const maps = MAP_IDS.map((id) => {
    const spots = thin(id, candidates(id));
    const land = landBitmap(id);
    const spotFile = spotBytes(spots);
    outputs[`contract/data/land-${id}.bin`] = land;
    outputs[`contract/data/spots-${id}.bin`] = spotFile;
    fileRows.push(`| land-${id}.bin | ${land.length} | ${toHex(sha256(land))} |`, `| spots-${id}.bin | ${spotFile.length} | ${toHex(sha256(spotFile))} |`);
    const rows = spots.map((s) => `[${s.x},${s.y},${s.tags},${s.kindMask}]`);
    return `    "${id}": {\n      "kinds": ${JSON.stringify(rosterOf(id))},\n      "landSha256": "${toHex(sha256(land))}",\n      "spotsSha256": "${toHex(sha256(spotFile))}",\n      "spots": [\n        ${rows.join(',\n        ')}\n      ]\n    }`;
  });
  outputs['src/lib/game/generated/map-data.json'] = `{\n  "maps": {\n${maps.join(',\n')}\n  }\n}\n`;
  outputs['contract/data/README.md'] = README(MAP_IDS.map(kindTable).join('\n\n'), fileRows.join('\n'));
  return outputs;
}
